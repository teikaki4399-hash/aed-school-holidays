def defined(t,i,L):
    rest=t[i+L:]; rest=re.sub(r'^(間内|時間内?|日|期間|時|中|休業日?|休暇|み)','',rest)
    return re.match(r'^\s*[(:：]\s*[^)]{0,25}?(\d|[月火水木金土日]曜|毎月|毎週)',rest) is not None
def amb(t):
    return {w for w in KW for m in re.finditer(re.escape(w),t) if not defined(t,m.start(),len(w))}
